import assert from 'node:assert/strict';
import {createGenesisHandlers} from '../lib/trading/one-global-r2-genesis-handler.mjs';
import {isOwnerAuthorized} from '../lib/ai/fenice-generative-research.ts';
import {createFeniceOwnerSession,feniceSessionCookieFromRequest,verifyFeniceOwnerSession,FENICE_AI_SESSION_COOKIE} from '../lib/ai/fenice-owner-session.ts';
const owner='unit-test-'+ 'x'.repeat(40), now=Date.parse('2026-11-27T17:00:00.000Z');
const url='https://example.test/api/paper/one-global-r2-prospective-genesis';
const body='{"action":"INITIALIZE_PAPER_GENESIS"}';
const cookie=FENICE_AI_SESSION_COOKIE+'='+createFeniceOwnerSession(owner,now);
const env={VERCEL_ENV:'production',FENICE_AI_OWNER_TOKEN:owner};
let writes=0, reads=0, present=false, broken=false;
const store={async initialize(){writes++;const created=!present;present=true;return {created};},async verifyCurrentSnapshot(){reads++;if(broken)throw Error('mock failure');return present?{verified:true,eventCount:0,historicalCredit:0}:null;}};
const {GET,POST}=createGenesisHandlers({env,isOwnerAuthorized,feniceSessionCookieFromRequest,verifyFeniceOwnerSession,createProspectiveR2PaperStore:()=>store,clock:()=>now});
const bearer={Authorization:'Bearer '+owner};
const browser={Cookie:cookie,Origin:new URL(url).origin,'x-fenice-diagnostic':'r2-prospective-genesis'};
const post=(headers={},payload=body)=>new Request(url,{method:'POST',headers:{'content-type':'application/json','content-length':String(Buffer.byteLength(payload)),...headers},body:payload});
async function check(response,status,state){assert.equal(response.status,status);assert.match(response.headers.get('cache-control'),/no-store/);const result=await response.json();assert.equal(result.state,state);assert.equal(result.liveTradingAllowed,false);assert.equal(result.brokerConnectivityAllowed,false);assert.equal(result.certifiedTrades,0);return result;}
await check(await GET(new Request(url)),401,'OWNER_AUTH_REQUIRED');
await check(await POST(post()),401,'OWNER_AUTH_REQUIRED');
await check(await POST(post({Authorization:'Bearer invalid'})),401,'OWNER_AUTH_REQUIRED');
await check(await POST(post({...browser,Origin:'https://evil.test'})),401,'OWNER_AUTH_REQUIRED');
await check(await POST(post({...browser,'x-fenice-diagnostic':'wrong'})),401,'OWNER_AUTH_REQUIRED');
await check(await POST(post(bearer,'{"action":"INVALID"}')),400,'GENESIS_REQUEST_INVALID');
await check(await POST(post({...bearer,'content-type':'text/plain'})),400,'GENESIS_REQUEST_INVALID');
env.VERCEL_ENV='preview';
await check(await POST(post(bearer)),403,'PRODUCTION_ONLY');
env.VERCEL_ENV='production';
assert.equal(writes,0);assert.equal(reads,0);
await check(await GET(new Request(url,{headers:bearer})),200,'R2_PROSPECTIVE_GENESIS_ABSENT');
assert.equal(writes,0);
assert.equal((await check(await POST(post(browser)),200,'R2_PROSPECTIVE_GENESIS_VERIFIED')).created,true);
assert.equal((await check(await POST(post(bearer)),200,'R2_PROSPECTIVE_GENESIS_VERIFIED')).created,false);
await check(await GET(new Request(url,{headers:{Cookie:cookie}})),200,'R2_PROSPECTIVE_GENESIS_PRESENT');
broken=true;
await check(await GET(new Request(url,{headers:bearer})),409,'R2_PROSPECTIVE_VERIFICATION_BLOCKED');
await check(await POST(post(bearer)),409,'R2_PROSPECTIVE_INITIALIZATION_BLOCKED_RECHECK');
console.log('R2 genesis HTTP authorization, isolation and idempotent recovery boundary: PASS (mock storage)');

const backupAction='{"action":"BACKUP_PAPER_JOURNAL"}';
let backupCalls=0,recoveryCalls=0;
store.backupCurrent=async()=>{backupCalls++;return {verified:true,backupAccountSeparated:false,digest:'f'.repeat(64),eventCount:0,startedAt:'2026-11-27T17:00:00.000Z'};};
store.verifyIndependentBackup=async()=>{recoveryCalls++;return {verified:true,backupAccountSeparated:false,eventCount:0,startedAt:'2026-11-27T17:00:00.000Z'};};
await check(await POST(post({},backupAction)),401,'OWNER_AUTH_REQUIRED');
await check(await POST(post({...browser,Origin:'https://evil.test'},backupAction)),401,'OWNER_AUTH_REQUIRED');
env.VERCEL_ENV='preview';
await check(await POST(post(bearer,backupAction)),403,'PRODUCTION_ONLY');
env.VERCEL_ENV='production';
assert.equal(backupCalls,0);
const previousWrites=writes;
const verifiedBackup=await check(await POST(post(browser,backupAction)),200,'R2_ENCRYPTED_BACKUP_VERIFIED');
assert.equal(verifiedBackup.verified,true);
assert.equal(verifiedBackup.backupAccountSeparated,false);
assert.equal(Object.hasOwn(verifiedBackup,'digest'),false);
assert.equal(backupCalls,1);
assert.equal(recoveryCalls,1);
assert.equal(writes,previousWrites);
store.verifyIndependentBackup=async()=>({verified:true,eventCount:1});
await check(await POST(post(bearer,backupAction)),409,'R2_ENCRYPTED_BACKUP_BLOCKED');
assert.equal(writes,previousWrites);
console.log('Independent backup owner-only HTTP boundary: PASS (mock storage).');
