assert.equal(run({identity:{...identity,sessionDate:"2026-11-05"}}).reason,"FILL_SESSION_DATE_MISMATCH");
assert.equal(run({fill:{...fill,price:1}}).reason,"FILL_PRICE_OUTSIDE_QUOTES");
