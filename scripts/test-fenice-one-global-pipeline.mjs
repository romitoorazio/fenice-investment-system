import assert from "node:assert/strict";
import {runPaperShadow} from "../lib/global/paper-shadow-pipeline.mjs";
const nowIso="2026-11-06T10:00:00.000Z";
const ledger={mode:"FENICE_ONE_GLOBAL_VIRTUAL_ONLY",liveTradingAllowed:false,brokerConnectivityAllowed:false,events:[]};
const identity={campaignId:"synthetic-contract",mic:"XMIL",instrumentId:"XMIL:TEST",sessionDate:"2026-11-06",strategyVersion:"v1",signalId:"s1"};
const calendarObservation={mic:"XMIL",zone:"Europe/Rome",sourceId:"synthetic-calendar",authoritative:true,observedAt:"2026-11-06T09:59:30.000Z",tradingDay:true,phase:"CONTINUOUS",opensAt:"2026-11-06T08:00:00.000Z",closesAt:"2026-11-06T16:30:00.000Z"};
const quotes=["family-a","family-b"].map((family,i)=>({mic:"XMIL",currency:"EUR",instrumentId:"XMIL:TEST",family,observedAt:"2026-11-06T09:59:30.000Z",bid:100+i*.01,ask:100.1+i*.01}));
const fxEvidence={sourceId:"synthetic-fx",base:"EUR",quote:"EUR",rate:1,observedAt:"2026-11-06T09:59:30.000Z"};
const fill={occurredAt:"2026-11-06T09:59:40.000Z",side:"BUY",price:100.1,quantity:2,fees:1,fxToEur:1};
const input={ledger,identity,calendarObservation,quotes,fxEvidence,fill,nowIso};
const run=x=>runPaperShadow({...input,...x});
const ok=run({});assert.equal(ok.added,true);assert.equal(ok.ledger.events.length,1);
assert.equal(run({calendarObservation:{...calendarObservation,verificationStatus:"PROVIDER_RESPONSE_UNVERIFIED"}}).reason,"CALENDAR_PROVIDER_UNVERIFIED");
assert.equal(run({fxEvidence:{...fxEvidence,verificationStatus:"PROVIDER_RESPONSE_UNVERIFIED"}}).reason,"FX_PROVIDER_UNVERIFIED");
assert.equal(run({quotes:[{...quotes[0],verificationStatus:"PROVIDER_RESPONSE_UNVERIFIED"},quotes[1]]}).reason,"PAPER_UNVERIFIED_PROVIDER_QUOTE");
assert.equal(run({ledger:ok.ledger}).reason,"DUPLICATE_PAPER_SIGNAL");
assert.equal(run({quotes:quotes.map(q=>({...q,observedAt:"2026-11-06T09:59:50.000Z"}))}).reason,"PAPER_FUTURE_EVIDENCE");
assert.equal(run({fxEvidence:{...fxEvidence,observedAt:"2026-11-06T09:59:50.000Z"}}).reason,"PAPER_FUTURE_EVIDENCE");
assert.equal(run({calendarObservation:{...calendarObservation,observedAt:"2026-11-06T09:59:50.000Z"}}).reason,"PAPER_FUTURE_EVIDENCE");
assert.equal(run({fill:{...fill,price:100.05}}).reason,"PAPER_BUY_BELOW_ASK");
assert.equal(run({fill:{...fill,side:"SELL",price:100.05}}).reason,"PAPER_SELL_ABOVE_BID");
assert.equal(run({fill:{...fill,side:"SELL",price:100.01}}).added,true);
assert.equal(run({identity:{...identity,sessionDate:"2026-11-05"}}).reason,"FILL_SESSION_DATE_MISMATCH");
assert.equal(run({fill:{...fill,price:1}}).reason,"FILL_PRICE_OUTSIDE_QUOTES");
assert.equal(run({fill:{...fill,price:1000}}).reason,"FILL_PRICE_OUTSIDE_QUOTES");
assert.equal(run({calendarObservation:{...calendarObservation,phase:"CLOSED"}}).reason,"MARKET_NOT_CONTINUOUS");
assert.equal(run({quotes:quotes.slice(0,1)}).added,false);
// Even fresh within 120 seconds, quotes recorded before the verified exchange open
// must not be treated as current-session executable prices.
const lateOpenCalendar={...calendarObservation,opensAt:"2026-11-06T09:59:35.000Z",observedAt:"2026-11-06T09:59:40.000Z"};
const lateFill={...fill,occurredAt:"2026-11-06T09:59:50.000Z"};
assert.equal(run({calendarObservation:lateOpenCalendar,fill:lateFill}).reason,"INDEPENDENT_FRESH_QUOTES_MISSING");
assert.equal(run({calendarObservation:lateOpenCalendar,fill:lateFill,quotes:[quotes[0],{...quotes[1],observedAt:"2026-11-06T09:59:45.000Z"}]}).reason,"INDEPENDENT_FRESH_QUOTES_MISSING");
assert.equal(run({fxEvidence:{...fxEvidence,rate:1.1}}).reason,"FX_CONSENSUS_MISMATCH");
assert.equal(run({fill:{...fill,fxToEur:1.1}}).reason,"FX_FILL_MISMATCH");
assert.equal(run({fxEvidence:{...fxEvidence,observedAt:"2026-11-06T09:00:00.000Z"}}).reason,"FX_EVIDENCE_INVALID_OR_STALE");
assert.equal(run({fill:{...fill,occurredAt:"2026-11-06T10:01:00.000Z"}}).reason,"FILL_OUTSIDE_VERIFIED_WINDOW");
assert.equal(run({ledger:{...ledger,liveTradingAllowed:true}}).reason,"LEDGER_SAFETY_INVALID");
// GBP PAPER requires two independent FX families known before the simulated fill.
const gbpIdentity={...identity,mic:"XLON",instrumentId:"XLON:TEST",signalId:"gbp-1"};
const gbpCalendar={...calendarObservation,mic:"XLON",zone:"Europe/London"};
const gbpQuotes=quotes.map(q=>({...q,mic:"XLON",currency:"GBP",instrumentId:"XLON:TEST"}));
const gbpFx={...fxEvidence,base:"GBP",rate:.8};
const gbpFill={...fill,fxToEur:.8};
const gbpObservations=["fx-a","fx-b"].map(family=>({base:"GBP",quote:"EUR",family,rate:.8,observedAt:"2026-11-06T09:59:30.000Z"}));
const gbpInput={...input,identity:gbpIdentity,calendarObservation:gbpCalendar,quotes:gbpQuotes,fxEvidence:gbpFx,fxObservations:gbpObservations,fill:gbpFill};
assert.equal(runPaperShadow(gbpInput).added,true);
assert.equal(runPaperShadow({...gbpInput,fxObservations:gbpObservations.map(q=>({...q,observedAt:"2026-11-06T09:59:50.000Z"}))}).reason,"PAPER_FUTURE_EVIDENCE");
console.log("Fenice ONE GLOBAL shadow pipeline synthetic contracts: PASS");
