import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { buildGlobalResearchDesk } from "../lib/ui/global-research-desk.ts";
const reference = JSON.parse(await readFile(new URL("../data/global-reference-coverage.json", import.meta.url),"utf8"));
const universe = JSON.parse(await readFile(new URL("../data/global-market-universe.json", import.meta.url),"utf8"));
const monday = Date.parse("2026-10-19T02:00:00Z");
const desk = buildGlobalResearchDesk(universe, reference, monday);
assert.equal(desk.summary.representedRegions, 5);
assert.equal(desk.summary.curatedVenues, 15);
assert.equal(desk.regions.length, 5);
assert.equal(desk.venues.length, 15);
assert.equal(new Set(desk.venues.map(x=>x.mic)).size, 15);
assert.equal(desk.summary.verifiedWorldExecutionVenues, 0);
assert.equal(desk.referenceState, "REVIEW_OUTDATED", "13 Oct reference snapshot is not current on 19 Oct");
assert.equal(desk.regions.find(x=>x.id==="asia-pacific").matchedCountries, 14);
assert.equal(desk.regions.find(x=>x.id==="asia-pacific").targetCountries, 30);
assert.equal(desk.venues.find(x=>x.mic==="XHKG").researchWindowCandidate, true);
assert.equal(desk.venues.find(x=>x.mic==="XLON").researchWindowCandidate, false);
assert.equal(desk.venues.find(x=>x.mic==="XNAS").researchWindowCandidate, false);
assert.equal(desk.regions.find(x=>x.id==="asia-pacific").attention, "REVIEW_NOW");
const europe = buildGlobalResearchDesk(universe, reference, Date.parse("2026-10-19T09:00:00Z"));
assert.equal(europe.venues.find(x=>x.mic==="XLON").researchWindowCandidate, true);
assert.equal(europe.venues.find(x=>x.mic==="XMIL").researchWindowCandidate, true);
assert.equal(europe.venues.find(x=>x.mic==="BVMF").researchWindowCandidate, false);
const america = buildGlobalResearchDesk(universe, reference, Date.parse("2026-10-19T14:00:00Z"));
assert.equal(america.venues.find(x=>x.mic==="BVMF").researchWindowCandidate, true);
assert.equal(america.venues.find(x=>x.mic==="XNYS").researchWindowCandidate, true);
assert.equal(america.venues.find(x=>x.mic==="XASX").researchWindowCandidate, false);
assert.equal(america.venues.find(x=>x.mic==="XNYS").marketTruth, "UNKNOWN", "time is not proof of exchange open");
assert.equal(america.summary.authoritativeOpenVenuesNow, 0);
const sunday = buildGlobalResearchDesk(universe, reference, Date.parse("2026-10-18T09:00:00Z"));
assert.equal(sunday.summary.indicativeResearchWindowsNow,0);
const futureReport = buildGlobalResearchDesk(universe, {...reference,generatedAt:"2026-10-25T09:00:00.000Z"},monday);
assert.equal(futureReport.referenceState,"UNVERIFIED");
const noProof = buildGlobalResearchDesk(universe,{...reference,safety:{...reference.safety,liveTradingAllowed:true}},monday);
assert.equal(noProof.locksValid,false);
assert(noProof.regions.every(x=>x.attention==="VERIFY_REFERENCE"));
const forged = buildGlobalResearchDesk(universe,{...reference,regionCoverage:reference.regionCoverage.map(x=>x.regionId==="europe"?{...x,providerMatchedCountries:999}:x)},monday);
assert.equal(forged.regions.find(x=>x.id==="europe").matchedCountries,null);
for(const row of desk.venues) {
  assert.equal(row.orderSubmissionAllowed,false);
  assert.equal(row.paperExecutionAllowed,false);
  assert.equal(row.brokerConnectivityAllowed,false);
  assert.equal(row.liveTradingAllowed,false);
  if (!["XNYS","XNAS","ARCX"].includes(row.mic)) assert.equal(row.marketTruth,"UNKNOWN");
}
assert.equal(desk.policy.liveTradingAllowed,false);
assert.equal(desk.policy.paperExecutionAllowed,false);
assert.equal(desk.policy.sessionsAreIndicativeNotActualOpen,true);
for(const path of ["../app/api/market/global-desk/route.ts","../app/global/page.tsx"]) {
  const src=await readFile(new URL(path,import.meta.url),"utf8");
  assert.match(src,/buildGlobalResearchDesk/);
  assert.doesNotMatch(src,/submitOrder|sendOrder|executeTrade|liveTradingAllowed:\s*true/);
}
console.log("Fenice global research desk, 15 venues, 5 regions, DST, ageing and execution lock: PASS");
