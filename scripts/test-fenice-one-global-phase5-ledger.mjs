import assert from "node:assert/strict";
import {appendPhase5VirtualLedger,validatePhase5PersistedLedger,reconcilePhase5PortfolioToLedger} from "../lib/global/phase5-virtual-ledger.mjs";
const trade={instrumentId:"XMIL:TEST",mic:"XMIL",entryAt:"2026-11-01T00:00:00Z",exitAt:"2026-11-05T00:00:00Z",netPnlEuro:3.25,entryPrice:10,exitPrice:11,quantity:3.25,classification:"HISTORICAL_SIMULATION_NOT_LIVE_FILL"};
const a=appendPhase5VirtualLedger({trades:[trade],recordedAt:"2026-11-10T00:00:00Z"});
assert.equal(a.appended,1);assert.equal(a.journal[0].trade.entryPrice,10);assert.equal(a.journal[0].trade.quantity,3.25);assert.equal(a.ordersGenerated,0);
const b=appendPhase5VirtualLedger({journal:a.journal,trades:[trade],recordedAt:"2026-11-10T00:00:00Z"});
assert.equal(b.appended,0);assert.equal(b.duplicates,1);
const tampered=structuredClone(a.journal);tampered[0].trade.netPnlEuro=999;
assert.throws(()=>appendPhase5VirtualLedger({journal:tampered}),/INTEGRITY/);
assert.throws(()=>appendPhase5VirtualLedger({trades:[{...trade,exitAt:"2026-12-01T00:00:00Z"}],recordedAt:"2026-11-10T00:00:00Z"}),/INVALID_PHASE5_VIRTUAL_TRADE/);
const envelope={schemaVersion:1,...a};
assert.equal(validatePhase5PersistedLedger(envelope,"2026-11-10T00:00:00Z").length,1);
assert.throws(()=>validatePhase5PersistedLedger({...envelope,headHash:"TAMPER"},"2026-11-10T00:00:00Z"),/HEAD_MISMATCH/);
const revised={...trade,exitPrice:12,netPnlEuro:6.5};
const replay=appendPhase5VirtualLedger({journal:a.journal,trades:[revised],recordedAt:"2026-11-10T00:00:00Z"});
assert.equal(replay.duplicates,1);assert.equal(replay.appended,0);
const current={mode:"PHASE5_HISTORICAL_VIRTUAL_PORTFOLIO_NOT_LIVE",initialCashEuro:1000,netPnlEuro:6.5,endingCashEuro:1006.5,trades:[revised],liveTradingAllowed:false,ordersGenerated:0};
const matched=reconcilePhase5PortfolioToLedger({portfolio:current,ledger:replay});
assert.equal(matched.trades[0].exitPrice,11);assert.equal(matched.trades[0].netPnlEuro,3.25);
assert.equal(matched.netPnlEuro,3.25);assert.equal(matched.endingCashEuro,1003.25);
assert.equal(matched.reconciliation.repricedDuplicateCount,1);
assert.throws(()=>reconcilePhase5PortfolioToLedger({portfolio:{...current,trades:[{...revised,instrumentId:"XMIL:UNKNOWN"}]},ledger:replay}),/TRADE_NOT_FOUND/);
const provisional={...trade,entryAt:"2026-11-04T08:00:00Z",exitAt:"2026-11-10T08:00:00Z"};
const legacy=appendPhase5VirtualLedger({trades:[provisional],recordedAt:"2026-11-10T13:00:00Z"});
assert.equal(legacy.integrityAudit.potentiallyUnsettled.length,1);
assert.equal(legacy.integrityAudit.authoritativeProfitClaim,false);
const reread=appendPhase5VirtualLedger({journal:legacy.journal,trades:[],recordedAt:"2026-11-11T13:00:00Z"});
assert.equal(reread.integrityAudit.potentiallyUnsettled.length,1);
console.log("FENICE phase5 virtual ledger integrity, dedupe and no lookahead: PASS");
