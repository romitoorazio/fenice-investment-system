import assert from "node:assert/strict";
import {rankGlobalResearchCandidates} from "../lib/global/phase3-global-research-ranker.mjs";
const nowIso="2026-11-10T10:00:00.000Z";
const candidate=(mic,instrumentId,momentum5dPct)=>({mic,instrumentId,momentum5dPct,momentum20dPct:4,volatility20dPct:3,spreadPct:.1,lastPrice:100,fxToEur:.01,observedAt:nowIso,synthetic:true});
const items=[candidate("XTKS","XTKS:7203",6),candidate("XMIL","XMIL:ENEL",4),candidate("XETR","XETR:SAP",5),candidate("XNYS","XNYS:TEST",3)];
const r=rankGlobalResearchCandidates({candidates:items,capitalEur:1000,nowIso});
assert.equal(r.ranked.length,4);
assert.equal(r.ranked[0].mic,"XTKS");
assert.equal(r.ranked[0].maxNotionalEur,100);
assert.equal(r.ranked[0].riskBudgetEur,10);
assert.equal(r.ranked[0].referenceQuantity,100);
assert.equal(r.liveTradingAllowed,false);assert.equal(r.paperFillAuthorized,false);
assert(r.ranked.every(x=>x.classification==="RESEARCH_ONLY_NOT_EXECUTABLE"));
const invalid=rankGlobalResearchCandidates({candidates:[{...items[0],synthetic:false,provenanceVerified:false},items[0],items[0],{...items[1],observedAt:"2026-11-01T10:00:00Z"}],capitalEur:1000,nowIso});
assert.equal(invalid.ranked.length,1);
assert.deepEqual(invalid.excluded.map(x=>x.reason),["UNVERIFIED_RESEARCH_SOURCE","DUPLICATE_INSTRUMENT","STALE_RESEARCH_DATA"]);
assert.throws(()=>rankGlobalResearchCandidates({candidates:items,capitalEur:0,nowIso}),/INVALID_RESEARCH_POLICY/);
assert.throws(()=>rankGlobalResearchCandidates({candidates:items,capitalEur:1000,perPositionRiskPct:20,nowIso}),/INVALID_RESEARCH_POLICY/);
console.log("FENICE phase 3 global research ranker: PASS");
