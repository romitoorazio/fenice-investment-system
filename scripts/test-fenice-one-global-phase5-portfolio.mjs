import assert from "node:assert/strict";
import {simulatePhase5Portfolio} from "../lib/global/phase5-virtual-portfolio.mjs";
import {parseEcb90DayReferenceXml} from "../lib/global/ecb-daily-fx-reference.mjs";
const closes=Array.from({length:31},(_,i)=>({observedAt:new Date(Date.parse("2026-09-01T12:00:00Z")+i*86400000).toISOString(),close:10+i}));
const base={mic:"XMIL",instrumentId:"XMIL:TEST",currency:"EUR",synthetic:false,provenanceVerified:false,closes};
const result=simulatePhase5Portfolio({histories:[base],initialCashEuro:1000,allocationPct:10,feeEuro:1,exitSessions:2});
assert.equal(result.realPaperCertified,false);assert.equal(result.ordersGenerated,0);
assert.equal(result.trades.length,0);assert.equal(result.pending.length,1);
const historical=simulatePhase5Portfolio({histories:[base],initialCashEuro:1000,allocationPct:10,feeEuro:1,exitSessions:2,mode:"HISTORICAL_BACKTEST"});
assert.equal(historical.trades.length,1);assert.equal(historical.pending.length,0);
assert.ok(historical.netPnlEuro>0);
assert.equal(simulatePhase5Portfolio({histories:[{...base,currency:"USD"}]}).trades.length,0);
assert.throws(()=>simulatePhase5Portfolio({allocationPct:200}),/INVALID_PHASE5_POLICY/);
assert.equal(simulatePhase5Portfolio({histories:[]}).endingCashEuro,1000);
const byDay=Array.from({length:31},(_,i)=>({observedAt:new Date(Date.parse("2026-09-01T08:00:00Z")+i*86400000).toISOString(),close:10+i}));
const sampled={...base,closes:byDay};
const asOfIso="2026-10-01T12:00:00Z";
const first=simulatePhase5Portfolio({histories:[sampled],mode:"HISTORICAL_BACKTEST",exitSessions:2,asOfIso});
const revisedIntraday=byDay.map((p,i)=>i===30?{...p,close:999}:p);
const second=simulatePhase5Portfolio({histories:[{...sampled,closes:revisedIntraday}],mode:"HISTORICAL_BACKTEST",exitSessions:2,asOfIso});
assert.deepEqual(first.trades,second.trades);
assert(first.trades.length>0);
assert(first.trades.every(t=>t.exitAt<"2026-10-01T00:00:00Z"));
assert.equal(first.assumptions.dailyBarPolicy,"EXCLUDE_UNSETTLED_CURRENT_UTC_DATE");
const fxXml=`<?xml version="1.0"?><gesmes:Envelope><gesmes:Sender><gesmes:name>European Central Bank</gesmes:name></gesmes:Sender><Cube><Cube time='2026-09-28'><Cube currency='JPY' rate='100'/></Cube><Cube time='2026-09-30'><Cube currency='JPY' rate='110'/></Cube></Cube></gesmes:Envelope>`;
const fxReference=parseEcb90DayReferenceXml(fxXml);
assert.equal(fxReference.ok,true);
const jpy={...sampled,mic:"XTKS",instrumentId:"XTKS:7203",currency:"JPY"};
const world=simulatePhase5Portfolio({histories:[jpy],mode:"HISTORICAL_BACKTEST",exitSessions:2,asOfIso:"2026-10-03T12:00:00Z",fxReference});
assert.equal(world.trades.length,1);
assert.equal(world.trades[0].currency,"JPY");
assert.equal(world.trades[0].fxEntry.referenceDate,"2026-09-28");
assert.equal(world.trades[0].fxExit.referenceDate,"2026-09-30");
assert.equal(world.trades[0].fxEntry.eligibleForExecution,false);
assert.equal(world.assumptions.fxConversion,"ECB_90_DAY_HISTORICAL_INDICATIVE_RESEARCH_ONLY");
assert.equal(simulatePhase5Portfolio({histories:[jpy],mode:"HISTORICAL_BACKTEST",exitSessions:2,asOfIso:"2026-10-03T12:00:00Z"}).trades.length,0);
assert.equal(simulatePhase5Portfolio({histories:[jpy],mode:"HISTORICAL_BACKTEST",exitSessions:2,asOfIso:"2026-10-03T12:00:00Z",fxReference:{...fxReference,days:[]}}).trades.length,0);
console.log("FENICE phase5 virtual portfolio isolation and pending outcome: PASS");
