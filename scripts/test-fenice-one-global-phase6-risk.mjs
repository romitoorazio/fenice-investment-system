import assert from "node:assert/strict";
import {assessPhase6ForwardRisk,PHASE6_POLICY} from "../lib/global/phase6-risk-monitor.mjs";
const e=(pnl,when)=>({event:{type:"CLOSE",instrumentId:"XMIL:TEST",netPnlEuro:pnl,recordedAt:when}});
const row1=e(7,"2026-11-01T10:00:00Z"),row2=e(-20,"2026-11-02T10:00:00Z");
const a=assessPhase6ForwardRisk({entries:[row1,row2],initialCashEuro:1000});
assert.equal(a.closedTrades,2);assert.equal(a.wins,1);assert.equal(a.losses,1);
assert.equal(a.maxRealizedDrawdownEuro,20);
assert.equal(a.maxRealizedDrawdownPct,2);
assert.equal(a.riskState,"ACTIVE");
assert.equal(a.haltNewVirtualEntries,false);
assert.equal(a.realPaperCertified,false);assert.equal(a.ordersGenerated,0);
const losses=[-20,-20,-20].map((n,i)=>e(n,"2026-11-0"+(i+1)+"T10:00:00Z"));
const lossStreak=assessPhase6ForwardRisk({entries:losses,initialCashEuro:1000});
assert.equal(lossStreak.currentConsecutiveLosses,3);
assert.equal(lossStreak.haltNewVirtualEntries,true);
assert.ok(lossStreak.haltReasons.includes("CONSECUTIVE_LOSSES_REACHED"));
assert.equal(lossStreak.maxRealizedDrawdownPct,6);
const dd=assessPhase6ForwardRisk({entries:[e(-105,"2026-11-03T12:00:00Z")],initialCashEuro:1000});
assert.equal(dd.haltNewVirtualEntries,true);
assert.ok(dd.haltReasons.includes("MAX_REALIZED_DRAWDOWN_REACHED"));
const recovered=assessPhase6ForwardRisk({entries:[...losses,e(40,"2026-11-07T12:00:00Z")],initialCashEuro:1000});
assert.equal(recovered.currentConsecutiveLosses,0);
assert.equal(recovered.haltNewVirtualEntries,false);
assert.throws(()=>assessPhase6ForwardRisk({entries:[{event:{type:"BOGUS"}}]}),/UNKNOWN_RISK_EVENT/);
assert.throws(()=>assessPhase6ForwardRisk({initialCashEuro:0}),/INVALID_PHASE6_RISK_INPUT/);
assert.equal(PHASE6_POLICY.maxConsecutiveLosses,3);
console.log("FENICE phase6 forward risk: closed-only drawdown, loss streak, watch, halt and isolation: PASS");
