import assert from "node:assert/strict";
import {appendVirtualFill,replayVirtualLedger} from "../lib/global/virtual-ledger.mjs";
import {summarizeVirtualPaperLedger} from "../lib/global/virtual-accounting.mjs";
const empty=()=>({mode:"FENICE_ONE_GLOBAL_VIRTUAL_ONLY",liveTradingAllowed:false,brokerConnectivityAllowed:false,events:[]});
const identity={campaignId:"synthetic-accounting-test",mic:"XMIL",instrumentId:"XMIL:TEST",sessionDate:"2026-11-06",strategyVersion:"v1",signalId:"s1"};
const evidence={allowed:true,venue:"XMIL",instrumentId:"XMIL:TEST"};
const fill={occurredAt:"2026-11-06T09:30:00.000Z",side:"BUY",price:100,quantity:2,fees:2,fxToEur:1};
const append=(ledger,suffix,trade,id=identity,proof=evidence)=>appendVirtualFill({
 ledger,identity:{...id,signalId:suffix},fill:trade,evidence:proof
}).ledger;
let ledger=append(empty(),"s1",fill);
assert.equal(replayVirtualLedger(ledger).valid,true);
const buyReport=summarizeVirtualPaperLedger({ledger,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"});
assert.equal(buyReport.ok,true);assert.equal(buyReport.cashEur,798);
assert.equal(buyReport.openBookCostEur,202);assert.equal(buyReport.realizedNetPnlEur,0);
assert.equal(buyReport.unrealizedPnlEur,null);
assert.equal(buyReport.investmentPerformanceCertified,false);
const sell1={...fill,side:"SELL",price:110,quantity:1,fees:1,occurredAt:"2026-11-06T09:31:00.000Z"};
ledger=append(ledger,"s2",sell1);
let outcome=summarizeVirtualPaperLedger({ledger,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"});
assert.equal(outcome.ok,true);
assert.equal(outcome.cashEur,907);
assert.equal(outcome.openBookCostEur,101);
assert.equal(outcome.realizedNetPnlEur,8,"SELL 110 less fee 1 and FIFO entry 101");
assert.equal(outcome.bookEquityEur,1008);
assert.equal(outcome.positions[0].quantity,1);
const sell2={...sell1,price:120,occurredAt:"2026-11-06T09:32:00.000Z"};
ledger=append(ledger,"s3",sell2);
outcome=summarizeVirtualPaperLedger({ledger,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"});
assert.equal(outcome.ok,true);
assert.equal(outcome.cashEur,1026);
assert.equal(outcome.realizedNetPnlEur,26);
assert.equal(outcome.openBookCostEur,0);
assert.equal(outcome.bookEquityEur,1026);
assert.equal(outcome.totalFeesEur,4);
assert.equal(outcome.positions.length,0);
assert.equal(outcome.closedFillWinRatePct,100);
assert.equal(outcome.eventCount,3);
assert.equal(outcome.countsTowardRealPaper,false);
// Idempotent retry has no effect on accounting or trade counts.
const retry=appendVirtualFill({ledger,identity:{...identity,signalId:"s3"},fill:sell2,evidence});
assert.equal(retry.added,false);
assert.equal(summarizeVirtualPaperLedger({ledger:retry.ledger,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"}).eventCount,3);
const check=(x,reason)=>assert.equal(summarizeVirtualPaperLedger({ledger,...x}).reason,reason);
check({initialCapitalEur:1000},"FEE_CURRENCY_POLICY_REQUIRED");
check({initialCapitalEur:1000,feeCurrency:"USD"},"FEE_CURRENCY_POLICY_REQUIRED");
check({initialCapitalEur:0,feeCurrency:"QUOTE_CURRENCY"},"INVALID_VIRTUAL_CAPITAL");
check({initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY",expectedCampaignId:"other"},"MIXED_VIRTUAL_CAMPAIGNS");
check({initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY",ledger:{...ledger,liveTradingAllowed:true}},"LEDGER_SAFETY_INVALID");
const short=append(empty(),"sell-short",sell1);
assert.equal(summarizeVirtualPaperLedger({ledger:short,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"}).reason,"VIRTUAL_SHORT_SELL_FORBIDDEN");
const underfunded=append(empty(),"buy-large",{...fill,quantity:100});
assert.equal(summarizeVirtualPaperLedger({ledger:underfunded,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"}).reason,"INSUFFICIENT_VIRTUAL_EUR_CAPITAL");
const retro=append(ledger,"retro",{...fill,occurredAt:"2026-11-06T09:30:30.000Z"});
assert.equal(summarizeVirtualPaperLedger({ledger:retro,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"}).reason,"NON_CHRONOLOGICAL_VIRTUAL_EVENTS");
const another=append(ledger,"different-campaign",{...fill,occurredAt:"2026-11-06T09:33:00.000Z"},{...identity,campaignId:"other"});
assert.equal(summarizeVirtualPaperLedger({ledger:another,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"}).reason,"MIXED_VIRTUAL_CAMPAIGNS");
// FX and local-currency fees must both be converted at each simulated execution.
const jpyId={...identity,mic:"XTKS",instrumentId:"XTKS:7203"};
const jpyEvidence={allowed:true,venue:"XTKS",instrumentId:"XTKS:7203"};
let jpy=append(empty(),"j1",{...fill,price:100,quantity:2,fees:1,fxToEur:.006},jpyId,jpyEvidence);
jpy=append(jpy,"j2",{...sell1,price:110,quantity:1,fees:1,fxToEur:.006,occurredAt:"2026-11-06T09:31:00.000Z"},jpyId,jpyEvidence);
const jpyResult=summarizeVirtualPaperLedger({ledger:jpy,initialCapitalEur:10,feeCurrency:"QUOTE_CURRENCY"});
assert.equal(jpyResult.ok,true);assert.equal(jpyResult.realizedNetPnlEur,.05);
assert.equal(jpyResult.positions[0].quantity,1);
assert.equal(jpyResult.markToMarketValueEur,null);
const jpyEurFees=summarizeVirtualPaperLedger({ledger:jpy,initialCapitalEur:10,feeCurrency:"EUR"});
assert.equal(jpyEurFees.ok,true);
assert.equal(jpyEurFees.realizedNetPnlEur,-1.44,
 "EUR-denominated commissions must not be converted using JPY FX");
assert.equal(jpyEurFees.cashEur,7.46);
assert.equal(jpyEurFees.totalFeesEur,2);
assert.equal(jpyEurFees.feeCurrencyPolicy,"EUR");
const forged={...ledger,events:[...ledger.events.slice(0,1),{...ledger.events[1],price:999},ledger.events[2]]};
assert.equal(summarizeVirtualPaperLedger({ledger:forged,initialCapitalEur:1000,feeCurrency:"QUOTE_CURRENCY"}).ok,false);
console.log("Fenice ONE GLOBAL funded virtual accounting contracts: PASS");
